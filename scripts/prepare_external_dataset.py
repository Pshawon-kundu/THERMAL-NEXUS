"""Audit and adapt external temperature datasets for THERMAL-NEXUS.

The source files in ``Datasets/`` are not natively model-ready: they have
source-specific schemas, inconsistent timestamp headers, and no
THERMAL-NEXUS state labels. This script converts only trustworthy temperature
traces into the canonical raw contract, preserving provenance. Labels are
then generated by the project's existing future-excursion policy; no source
label is silently renamed to ``thermal_state``.

Usage::

    .venv/bin/python scripts/prepare_external_dataset.py --audit-only
    .venv/bin/python scripts/prepare_external_dataset.py --convert
    .venv/bin/python scripts/prepare_external_dataset.py --convert --include-elm
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path
from typing import Any

import pandas as pd

from ml.features.extract_features import add_features, load_feature_config
from ml.preprocessing.create_labels import add_labels, load_label_config
from ml.preprocessing.build_dataset import _model_ready_columns

ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = ROOT / "Datasets"
OUTPUT_ROOT = ROOT / "ml" / "data" / "external" / "thermal_nexus"
RAW_DIR = OUTPUT_ROOT / "raw"
PROCESSED_DIR = OUTPUT_ROOT / "processed"
AUDIT_PATH = OUTPUT_ROOT / "dataset_audit.json"

ELM_PATH = SOURCE_ROOT / "sample_temperature-ELM_v1.0_optimizationComp_data.csv"
NEPAL_ROOT = SOURCE_ROOT / (
    "Long-range freeze-preventive vaccine carriers in Nepal thermal data"
) / "Vaccine carrier temperature data"


def _stable_id(path: Path, prefix: str) -> str:
    digest = hashlib.sha1(str(path.relative_to(SOURCE_ROOT)).encode()).hexdigest()[:10]
    return f"external_{prefix}_{digest}"


def _read_nepal(path: Path) -> pd.DataFrame:
    """Read both Nepal logger variants, including note-prefixed files."""

    text = path.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    header_index = next(
        (i for i, line in enumerate(lines) if "Index" in line and "Date" in line),
        None,
    )
    if header_index is None:
        return pd.DataFrame()
    from io import StringIO

    frame = pd.read_csv(StringIO("\n".join(lines[header_index:])))
    frame.columns = [str(column).strip() for column in frame.columns]
    temperature_column = next(
        (column for column in frame.columns if "Readings" in column), None
    )
    if temperature_column is None:
        return pd.DataFrame()
    date_column = next((column for column in frame.columns if column == "Date"), None)
    time_column = next((column for column in frame.columns if column == "Time"), None)
    if date_column is None or time_column is None:
        return pd.DataFrame()
    timestamp = pd.to_datetime(
        frame[date_column].astype(str) + " " + frame[time_column].astype(str),
        errors="coerce",
        format="mixed",
        utc=True,
    )
    temperature = pd.to_numeric(frame[temperature_column], errors="coerce")
    result = pd.DataFrame({"timestamp": timestamp, "temperature": temperature})
    return result.dropna(subset=["timestamp", "temperature"])
    result = pd.DataFrame({"timestamp": timestamp, "temperature": temperature})
    return result.dropna(subset=["timestamp", "temperature"])


def _read_elm(path: Path) -> pd.DataFrame:
    frame = pd.read_csv(path)
    frame.columns = [str(column).strip() for column in frame.columns]
    temperature = pd.to_numeric(frame["Object_Temperature"], errors="coerce")
    # Serial_Reading is an ordering index, not a wall-clock timestamp. Use a
    # documented fixed interval so rolling features have meaningful units.
    timestamp = pd.Timestamp("2026-01-01", tz="UTC") + pd.to_timedelta(
        pd.to_numeric(frame["Serial_Reading"], errors="coerce") - 1, unit="min"
    )
    return pd.DataFrame({"timestamp": timestamp, "temperature": temperature}).dropna()


def audit_sources() -> dict[str, Any]:
    """Audit supplied files without modifying them."""

    csv_files = sorted(SOURCE_ROOT.rglob("*.csv"))
    records: list[dict[str, Any]] = []
    for path in csv_files:
        relative = str(path.relative_to(ROOT))
        if path == ELM_PATH:
            frame = _read_elm(path)
            records.append(
                {
                    "path": relative,
                    "source_type": "ELM_temperature",
                    "compatible_raw_contract": bool(len(frame)),
                    "rows": int(len(frame)),
                    "temperature_min_c": float(frame.temperature.min()),
                    "temperature_max_c": float(frame.temperature.max()),
                    "target_status": "source Critical_Level is binary and not mapped",
                }
            )
            continue
        if NEPAL_ROOT in path.parents:
            frame = _read_nepal(path)
            records.append(
                {
                    "path": relative,
                    "source_type": "Nepal_vaccine_carrier",
                    "compatible_raw_contract": bool(len(frame)),
                    "rows": int(len(frame)),
                    "temperature_min_c": float(frame.temperature.min()) if len(frame) else None,
                    "temperature_max_c": float(frame.temperature.max()) if len(frame) else None,
                    "target_status": "no native THERMAL-NEXUS state label",
                }
            )
    compatible = [record for record in records if record["compatible_raw_contract"]]
    result = {
        "source_root": str(SOURCE_ROOT),
        "csv_count": len(csv_files),
        "audited_csv_count": len(records),
        "compatible_temperature_trace_count": len(compatible),
        "source_types": {
            source: sum(record["source_type"] == source for record in records)
            for source in sorted({record["source_type"] for record in records})
        },
        "records": records,
        "policy": (
            "External source labels are not treated as THERMAL-NEXUS labels. "
            "Canonical labels are generated only after normalization by the "
            "existing future-excursion labeling policy."
        ),
    }
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    AUDIT_PATH.write_text(json.dumps(result, indent=2), encoding="utf-8")
    return result


def _normalize_trace(
    trace: pd.DataFrame,
    run_id: str,
    source_type: str,
    source_path: str,
    *,
    sample_interval_minutes: int = 10,
) -> pd.DataFrame:
    trace = trace.sort_values("timestamp").drop_duplicates("timestamp")
    if len(trace) < 30:
        return pd.DataFrame()
    # Resampling prevents irregular Nepal logger timestamps from producing
    # misleading derivatives. ELM is already one-minute data and is retained.
    indexed = trace.set_index("timestamp")[["temperature"]].resample(
        f"{sample_interval_minutes}min"
    ).mean().interpolate(limit=2)
    indexed = indexed.dropna().reset_index()
    if len(indexed) < 30:
        return pd.DataFrame()
    lower_limit = 2.0
    upper_limit = 8.0
    return pd.DataFrame(
        {
            "timestamp": pd.to_datetime(indexed.timestamp, utc=True),
            "run_id": run_id,
            "scenario": "external_observation",
            "true_temperature": indexed.temperature.astype(float),
            "measured_temperature": indexed.temperature.astype(float),
            "noise": 0.0,
            "lower_limit": lower_limit,
            "upper_limit": upper_limit,
            "event_started": False,
            "event_time": pd.NA,
            "sensor_valid": True,
            "random_seed": int(hashlib.sha1(run_id.encode()).hexdigest()[:8], 16),
            "data_source_type": source_type,
            "source_path": source_path,
        }
    )


def convert_sources(*, include_elm: bool = False, max_nepal_files: int | None = None) -> dict[str, Any]:
    """Normalize usable source traces and build canonical labels/features."""

    RAW_DIR.mkdir(parents=True, exist_ok=True)
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    paths: list[tuple[Path, str]] = []
    if include_elm and ELM_PATH.exists():
        paths.append((ELM_PATH, "ELM_temperature"))
    nepal_paths = sorted(NEPAL_ROOT.rglob("*.csv"))
    if max_nepal_files is not None:
        nepal_paths = nepal_paths[:max_nepal_files]
    paths.extend((path, "Nepal_vaccine_carrier") for path in nepal_paths)

    normalized: list[pd.DataFrame] = []
    manifest: list[dict[str, Any]] = []
    for path, source_type in paths:
        trace = _read_elm(path) if source_type == "ELM_temperature" else _read_nepal(path)
        run_id = _stable_id(path, "elm" if source_type.startswith("ELM") else "nepal")
        normalized_frame = _normalize_trace(
            trace,
            run_id,
            source_type,
            str(path.relative_to(ROOT)),
            sample_interval_minutes=1 if source_type.startswith("ELM") else 10,
        )
        if normalized_frame.empty:
            continue
        normalized_frame.to_csv(RAW_DIR / f"{run_id}.csv", index=False)
        normalized.append(normalized_frame)
        manifest.append(
            {
                "run_id": run_id,
                "source_type": source_type,
                "source_path": str(path.relative_to(ROOT)),
                "rows": len(normalized_frame),
            }
        )

    if not normalized:
        raise RuntimeError("No usable external temperature traces found.")
    raw = pd.concat(normalized, ignore_index=True)
    labels = add_labels(raw, load_label_config(ROOT / "config/labeling.yaml"))
    featured = add_features(labels, load_feature_config(ROOT / "config/features.yaml"))
    model_ready = _model_ready_columns(
        featured, load_label_config(ROOT / "config/labeling.yaml").prediction_horizons_minutes
    )
    featured.to_csv(PROCESSED_DIR / "labeled_feature_rows.csv", index=False)
    model_ready.to_csv(PROCESSED_DIR / "model_ready_dataset.csv", index=False)
    (PROCESSED_DIR / "source_manifest.json").write_text(
        json.dumps(
            {
                "runs": manifest,
                "row_count": len(raw),
                "feature_valid_count": int(featured.feature_valid.sum()),
                "label_distribution": featured.thermal_state.value_counts(dropna=False).to_dict(),
                "warning": (
                    "External observations are domain-shift evidence, not a replacement "
                    "for the synthetic training corpus. Labels are policy-derived."
                ),
            },
            indent=2,
            default=str,
        ),
        encoding="utf-8",
    )
    return {
        "run_count": len(manifest),
        "raw_rows": len(raw),
        "feature_valid_rows": int(featured.feature_valid.sum()),
        "model_ready_rows": len(model_ready),
        "label_distribution": featured.thermal_state.value_counts(dropna=False).to_dict(),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--audit-only", action="store_true")
    parser.add_argument("--convert", action="store_true")
    parser.add_argument("--include-elm", action="store_true")
    parser.add_argument("--max-nepal-files", type=int, default=None)
    args = parser.parse_args()
    if not args.audit_only and not args.convert:
        parser.error("choose --audit-only or --convert")
    audit = audit_sources()
    print(json.dumps({"audit": {
        "csv_count": audit["csv_count"],
        "audited_csv_count": audit["audited_csv_count"],
        "compatible_temperature_trace_count": audit["compatible_temperature_trace_count"],
        "source_types": audit["source_types"],
    }}, indent=2))
    if args.convert:
        print(json.dumps({"conversion": convert_sources(
            include_elm=args.include_elm,
            max_nepal_files=args.max_nepal_files,
        )}, indent=2, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
